#!/usr/bin/env bash
# Stage 37 — build the macro plugins a macro-enabled swift-frontend.wasm runs, as
# WebAssembly (only when SWIFT_MACROS=1).
#
# A native compiler runs macros in plugin processes or libraries built for the
# machine it runs on. The wasm-hosted compiler cannot start a process or load a
# library: its embedder runs the plugins (tools/plugin-host), so they have to be
# wasm too. swift-syntax supports exactly that (swift-syntax#2623): a plugin built
# for wasm32-wasip1 is a WASI command whose `_start` registers the handler and
# whose `swift_wasm_macro_v1_pump` export answers one message.
#
# One module serves every macro module this toolchain knows, so swift-syntax
# (most of a plugin's size) is in it once:
#
#   ObservationMacros  @Observable, from the Swift repository (lib/Macros)
#   TestingMacros      @Test, @Suite, #expect, #require..., from swift-testing,
#                      the same tag as the Testing library in the Swift SDK
#   StringifyMacros    #stringify and #diagnose, an example for tests
#
# The package is tools/macro-plugins/Package.swift; this stage copies the plugin
# sources next to it, generates the shared entry point, and builds it with the
# native toolchain and the Swift SDK for WebAssembly (the same SDK Stage 40 packs).
source "$(dirname "${BASH_SOURCE[0]}")/../env.sh"

if [[ "${SWIFT_MACROS:-0}" != "1" ]]; then
  log "macro support is off (SWIFT_MACROS=${SWIFT_MACROS:-0}); no plugins to build"
  exit 0
fi

: "${SWIFT_SRC:=${TC_SRC}/swift}"
: "${SWIFT_SYNTAX_SRC:=${TC_SRC}/swift-syntax}"
: "${SWIFT_TESTING_SRC:=${TC_SRC}/swift-testing}"
: "${NATIVE_SWIFT_BIN:=${HOME}/.local/share/swiftly/toolchains/${SWIFT_VERSION}/usr/bin}"

for dir in "$SWIFT_SYNTAX_SRC" "$SWIFT_TESTING_SRC/Sources/TestingMacros" \
           "$SWIFT_SRC/lib/Macros/Sources/ObservationMacros"; do
  [[ -d "$dir" ]] || die "missing ${dir}; run 00-fetch-sources.sh with SWIFT_MACROS=1"
done
[[ -x "${NATIVE_SWIFT_BIN}/swift" ]] || die "no native Swift toolchain at ${NATIVE_SWIFT_BIN}"

source "${TOOLCHAIN_ROOT}/scripts/wasm-sdk.sh"
fetch_wasm_sdk

STAGE="${TC_BUILD}/macro-plugins"
PACKAGE="${TOOLCHAIN_ROOT}/tools/macro-plugins"

log "staging the plugin package"
mkdir -p "${STAGE}/Sources"
cp "${PACKAGE}/Package.swift" "${STAGE}/"
# Replace the sources wholesale, keeping .build so swift-syntax is not rebuilt.
rm -rf "${STAGE}/Sources"/*
cp -R "${PACKAGE}/Sources/StringifyMacros" "${STAGE}/Sources/"
mkdir -p "${STAGE}/Sources/ObservationMacros" "${STAGE}/Sources/TestingMacros"
cp "${SWIFT_SRC}/lib/Macros/Sources/ObservationMacros/"*.swift "${STAGE}/Sources/ObservationMacros/"
cp -R "${SWIFT_TESTING_SRC}/Sources/TestingMacros/." "${STAGE}/Sources/TestingMacros/"
# swift-testing's own entry point is replaced by the shared one below.
rm -f "${STAGE}/Sources/TestingMacros/TestingMacrosMain.swift" \
      "${STAGE}/Sources/TestingMacros/CMakeLists.txt"

# The shared entry point lists every macro type each module provides. The lists
# come from the sources, so a new swift-testing tag needs no edit here:
# TestingMacros' from its own entry point, the others' from their public types.
testing_macros="$(sed -n 's/^ *\([A-Za-z]*\)\.self,$/\1/p' \
  "${SWIFT_TESTING_SRC}/Sources/TestingMacros/TestingMacrosMain.swift")"
public_macros() {
  sed -n 's/^public struct \([A-Za-z]*Macro\)\b.*/\1/p' "$@"
}
observation_macros="$(public_macros "${STAGE}/Sources/ObservationMacros/"*.swift)"
stringify_macros="$(public_macros "${STAGE}/Sources/StringifyMacros/"*.swift)"
[[ -n "$testing_macros" && -n "$observation_macros" && -n "$stringify_macros" ]] ||
  die "could not list the macros each plugin provides"

mkdir -p "${STAGE}/Sources/SwiftMacroPlugins"
{
  cat <<'SWIFT'
// Generated by scripts/37-macro-plugins.sh: the entry point of the wasm macro
// plugin that serves ObservationMacros, TestingMacros and StringifyMacros.
import ObservationMacros
import StringifyMacros
import SwiftCompilerPlugin
import SwiftSyntaxMacros
import TestingMacros

@main
struct SwiftMacroPlugins: CompilerPlugin {
  var providingMacros: [any Macro.Type] {
    [
SWIFT
  for m in $observation_macros; do echo "      ObservationMacros.${m}.self,"; done
  for m in $testing_macros; do echo "      TestingMacros.${m}.self,"; done
  for m in $stringify_macros; do echo "      StringifyMacros.${m}.self,"; done
  cat <<'SWIFT'
    ]
  }
}
SWIFT
} > "${STAGE}/Sources/SwiftMacroPlugins/SwiftMacroPlugins.swift"

log "building SwiftMacroPlugins for ${WASM_TARGET} (swift-syntax included; ~10 minutes cold)"
SWIFT_SYNTAX_PATH="$SWIFT_SYNTAX_SRC" "${NATIVE_SWIFT_BIN}/swift" build \
  --package-path "$STAGE" \
  --configuration release \
  --swift-sdks-path "$WASM_SDK_ROOT" \
  --swift-sdk "$WASM_SDK_ID" \
  -Xswiftc -Osize \
  --jobs "$JOBS"

built="$(find "${STAGE}/.build" -path '*release/SwiftMacroPlugins.wasm' -type f -print -quit)"
[[ -f "$built" ]] || die "swift build produced no SwiftMacroPlugins.wasm"

# Names and debug info are most of an unstripped plugin; the host needs neither.
"${WASI_SDK_PATH}/bin/llvm-strip" -o "${TC_OUT}/SwiftMacroPlugins.wasm" "$built"
log "wrote ${TC_OUT}/SwiftMacroPlugins.wasm ($(du -h "${TC_OUT}/SwiftMacroPlugins.wasm" | cut -f1))"
